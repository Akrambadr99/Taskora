import { expect, test } from '@playwright/test'

test('manages a dependency from both issue details and edits hierarchy', async ({ page }) => {
  await page.goto('/issues')
  const row = page.getByRole('table', { name: 'Workspace issues' }).getByRole('row').nth(1)
  await row.getByRole('link').first().click()
  const panel = page.getByRole('region', { name: 'Dependencies and hierarchy' })
  await expect(panel.getByLabel('Target issue')).toBeEnabled()
  const options = panel.getByLabel('Target issue').locator('option')
  const targetId = await options.nth(1).getAttribute('value')
  if (!targetId) throw new Error('Expected same-project relationship candidate.')
  await panel.getByRole('combobox', { name: 'Relationship', exact: true }).selectOption('duplicates')
  await panel.getByLabel('Target issue').selectOption(targetId)
  await panel.getByRole('button', { name: 'Add relationship' }).click()
  await expect(panel.getByText('Relationships saved.')).toBeVisible()
  const linked = panel.getByRole('list', { name: 'Linked issues' }).getByRole('listitem').filter({ hasText: 'Duplicates:' })
  await linked.getByRole('link').click()
  await expect(page).toHaveURL(`/issues/${targetId}`)
  const inverse = panel.getByRole('list', { name: 'Linked issues' }).getByRole('listitem').filter({ hasText: 'Duplicated by:' })
  await inverse.getByRole('button', { name: /Remove duplicated by/ }).click()
  await expect(panel.getByText('Relationships saved.')).toBeVisible()
  await expect(inverse).toHaveCount(0)
  const parentId = await panel.getByLabel('Parent issue').locator('option').nth(1).getAttribute('value')
  if (!parentId) throw new Error('Expected parent candidate.')
  await panel.getByLabel('Parent issue').selectOption(parentId)
  await panel.getByRole('button', { name: 'Save parent' }).click()
  await expect(panel.getByRole('button', { name: 'Save parent' })).toBeDisabled()
  await expect(panel.getByLabel('Parent issue')).toHaveValue(parentId)
  await panel.getByLabel('Parent issue').selectOption('')
  await panel.getByRole('button', { name: 'Save parent' }).click()
  await expect(panel.getByLabel('Parent issue')).toHaveValue('')
  await expect(panel.getByRole('button', { name: 'Save parent' })).toBeDisabled()
})
